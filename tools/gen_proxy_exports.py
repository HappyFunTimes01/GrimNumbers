#!/usr/bin/env python3
"""Generate a complete pass-through export table for a proxy DLL.

Why this exists
---------------
A proxy DLL replaces a system DLL *for the whole process*, not just for the
program you care about. Exporting only the handful of functions the game
itself imports makes the loader fail some *other* module's imports with
"Entry Point Not Found", which kills the game before its window appears.

That is not hypothetical: the first version of this proxy shadowed winmm.dll
and exported only the three functions Grim Dawn's own modules import. Steam
injects steamclient64.dll, which imports waveOutGetDevCapsW and the whole
mixer* family, so the game died at startup in a relaunch loop. Counting
importers in the live process settled the design:

    winmm.dll     181 exports, 8 consumers (exe, SHELL32, Engine, Game,
                  Steam overlay, steamclient64, two NVIDIA driver DLLs)
    dinput8.dll     6 exports, 1 consumer (Crate's own directinput.dll)

So the proxy shadows dinput8.dll, and exports *all* of it regardless. This
script reads the export directory of the system DLL straight out of the PE (no
dumpbin dependency) and emits:

  proxy_exports.def    every export, at its original ordinal, pointing at a thunk
  proxy_thunks.asm     one `jmp [target]` thunk per export (MASM, x64)
  proxy_targets.cpp    the target table plus the names used to resolve it

Each thunk is a bare indirect jump, so it is signature-agnostic: arguments stay
in their registers and on the stack, and the return goes straight to the
original caller. That is what makes it safe to forward functions whose
prototypes we never declare.

The table is generated from the *local* system DLL at build time, so the proxy
always matches the Windows version it is built on.
"""

import os
import struct
import sys


def read_exports(path):
    """Return (ordinal_base, [(ordinal, name_or_None)]) from a PE export table."""
    with open(path, "rb") as f:
        d = f.read()

    pe = struct.unpack_from("<I", d, 0x3C)[0]
    if d[pe:pe + 4] != b"PE\0\0":
        raise SystemExit(f"{path}: not a PE file")

    magic = struct.unpack_from("<H", d, pe + 24)[0]
    if magic != 0x20B:
        raise SystemExit(f"{path}: not PE32+ (x64); magic 0x{magic:X}")

    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    optsz = struct.unpack_from("<H", d, pe + 20)[0]
    # Export directory is data directory 0, which sits at optional-header+112
    # for PE32+.
    exp_rva, _exp_size = struct.unpack_from("<II", d, pe + 24 + 112)

    sections = []
    off = pe + 24 + optsz
    for i in range(nsec):
        b = d[off + i * 40: off + (i + 1) * 40]
        vsz, va, rsz, raw = struct.unpack_from("<IIII", b, 8)
        sections.append((va, max(vsz, rsz), raw))

    def rva2off(rva):
        for va, size, raw in sections:
            if va <= rva < va + size:
                return raw + (rva - va)
        raise SystemExit(f"rva 0x{rva:X} outside all sections")

    e = rva2off(exp_rva)
    base = struct.unpack_from("<I", d, e + 16)[0]
    n_funcs = struct.unpack_from("<I", d, e + 20)[0]
    n_names = struct.unpack_from("<I", d, e + 24)[0]
    addr_rva = struct.unpack_from("<I", d, e + 28)[0]
    names_rva = struct.unpack_from("<I", d, e + 32)[0]
    ords_rva = struct.unpack_from("<I", d, e + 36)[0]

    # ordinal index -> name, for the entries that have one
    by_index = {}
    names_off = rva2off(names_rva)
    ords_off = rva2off(ords_rva)
    for i in range(n_names):
        name_rva = struct.unpack_from("<I", d, names_off + i * 4)[0]
        idx = struct.unpack_from("<H", d, ords_off + i * 2)[0]
        o = rva2off(name_rva)
        end = d.index(b"\0", o)
        by_index[idx] = d[o:end].decode("ascii")

    out = []
    addr_off = rva2off(addr_rva)
    for i in range(n_funcs):
        fn_rva = struct.unpack_from("<I", d, addr_off + i * 4)[0]
        if fn_rva == 0:
            continue  # hole in the ordinal range
        out.append((base + i, by_index.get(i)))
    return base, out


def main():
    if len(sys.argv) < 4:
        raise SystemExit("usage: gen_proxy_exports.py <system dll> <out dir> <libname>")
    src, outdir, libname = sys.argv[1], sys.argv[2], sys.argv[3]
    os.makedirs(outdir, exist_ok=True)

    _base, exports = read_exports(src)
    named = [(o, n) for o, n in exports if n]
    unnamed = [(o, n) for o, n in exports if not n]
    print(f"gen_proxy_exports: {len(exports)} exports "
          f"({len(named)} named, {len(unnamed)} ordinal-only) from {src}")

    # ---- thunks (MASM x64) ----
    asm = [
        "; Generated by tools/gen_proxy_exports.py - do not edit.",
        "; One indirect jump per proxied export. Signature-agnostic: arguments stay",
        "; where the caller put them and the callee returns straight to the caller.",
        "",
        "EXTERN gn_proxy_targets:QWORD",
        "",
        ".code",
        "",
    ]
    for i, (ordinal, name) in enumerate(exports):
        label = f"gn_thunk_{i:03d}"
        asm.append(f"{label} PROC            ; @{ordinal} {name or '[NONAME]'}")
        asm.append(f"    jmp QWORD PTR [gn_proxy_targets + {i} * 8]")
        asm.append(f"{label} ENDP")
    asm.append("")
    asm.append("END")
    with open(os.path.join(outdir, "proxy_thunks.asm"), "w", newline="\r\n") as f:
        f.write("\n".join(asm))

    # ---- .def ----
    d = [
        "; Generated by tools/gen_proxy_exports.py - do not edit.",
        "LIBRARY " + libname,
        "",
        "EXPORTS",
    ]
    # The linker warns (LNK4104) if the standard COM/self-registration entry
    # points go into the import library. PRIVATE still exports them, which is
    # all a proxy needs.
    com_entries = {
        "DllCanUnloadNow", "DllGetClassObject",
        "DllRegisterServer", "DllUnregisterServer", "DllInstall",
    }
    for i, (ordinal, name) in enumerate(exports):
        label = f"gn_thunk_{i:03d}"
        if name:
            priv = " PRIVATE" if name in com_entries else ""
            d.append(f"    {name} = {label} @{ordinal}{priv}")
        else:
            d.append(f"    {label} @{ordinal} NONAME PRIVATE")
    with open(os.path.join(outdir, "proxy_exports.def"), "w", newline="\r\n") as f:
        f.write("\n".join(d) + "\n")

    # ---- target table ----
    c = [
        "// Generated by tools/gen_proxy_exports.py - do not edit.",
        "#include <windows.h>",
        "#include <stdint.h>",
        "",
        "// Returning 0 is the least harmful thing a never-resolved export can do.",
        "// In practice this should stay unused; the log names any export that",
        "// failed to resolve.",
        'extern "C" uintptr_t gn_proxy_unresolved(void) { return 0; }',
        "",
        f"#define GN_PROXY_COUNT {len(exports)}",
        "",
        "// Statically pointed at the stub so a call that somehow lands before",
        "// DllMain populates the table jumps somewhere valid instead of to null.",
        'extern "C" void* gn_proxy_targets[GN_PROXY_COUNT] = {',
    ]
    c += ["    (void*)&gn_proxy_unresolved," for _ in exports]
    c.append("};")
    c.append("")
    c.append("// Name for each slot; null means the export is ordinal-only.")
    c.append("extern \"C\" const char* const gn_proxy_names[GN_PROXY_COUNT] = {")
    for _o, n in exports:
        c.append(f'    "{n}",' if n else "    nullptr,")
    c.append("};")
    c.append("")
    c.append('extern "C" const unsigned short gn_proxy_ordinals[GN_PROXY_COUNT] = {')
    for o, _n in exports:
        c.append(f"    {o},")
    c.append("};")
    c.append("")
    c.append('extern "C" const int gn_proxy_count = GN_PROXY_COUNT;')
    with open(os.path.join(outdir, "proxy_targets.cpp"), "w", newline="\r\n") as f:
        f.write("\n".join(c) + "\n")

    print(f"gen_proxy_exports: wrote proxy_thunks.asm, proxy_exports.def, "
          f"proxy_targets.cpp to {outdir}")


if __name__ == "__main__":
    main()
